FOUNDATIONS = [lesson for lesson in lessons() if lesson["module_id"] == "python-foundations-module"]
PROJECT_ROOT = settings.content_dir / "projects" / "expense-tracker"


class FoundationsContentTests(unittest.TestCase):
    def test_nine_ordered_lessons_have_teaching_tasks_and_distinct_exercises(self):
        self.assertEqual(len(FOUNDATIONS), 9)
        self.assertEqual(sum(len(lesson["exercises"]) for lesson in FOUNDATIONS), 18)
        for index, lesson in enumerate(FOUNDATIONS):
            self.assertEqual(lesson["prerequisites"], [] if index == 0 else [FOUNDATIONS[index - 1]["id"]])
            body = (settings.content_dir / lesson["path"]).read_text()
            for marker in ["## Guided practice", "## Independent", "```python"]:
                self.assertIn(marker, body)
            for target in re.findall(r"\]\(/lessons/([a-z-]+)\)", body):
                self.assertIn(target, {item["id"] for item in lessons()})
        exams = [catalog()["exam"]] + [
            json.loads(p.read_text()) for p in (settings.content_dir / "assessments").glob("*.json")
        ]
        practice = {q["prompt"] for lesson in FOUNDATIONS for q in lesson["exercises"]}
        self.assertFalse(practice & {q["prompt"] for exam in exams for q in exam["questions"]})

    def test_authored_lesson_examples_execute_with_their_assertions(self):
        # Trusted repository examples only, executed outside the API in temporary directories.
        for lesson in FOUNDATIONS:
            with self.subTest(lesson=lesson["id"]), tempfile.TemporaryDirectory() as directory:
                body = (settings.content_dir / lesson["path"]).read_text()
                blocks = re.findall(r"```python\n(.*?)```", body, flags=re.S)
                code = "\n\n".join(blocks)
                if lesson["id"] == "python-tests":
                    code += "\nresult = unittest.TextTestRunner().run(unittest.defaultTestLoader.loadTestsFromTestCase(CategoryTests))\nassert result.wasSuccessful()\n"
                run = subprocess.run(
                    [sys.executable, "-I", "-c", code],
                    cwd=directory,
                    capture_output=True,
                    text=True,
                    timeout=5,
                )
                self.assertEqual(run.returncode, 0, run.stderr)

    def test_public_acceptance_suite_passes_reference_and_detects_incomplete_starter(self):
        with tempfile.TemporaryDirectory() as directory:
            root = Path(directory) / "project"
            shutil.copytree(PROJECT_ROOT / "starter", root, ignore=shutil.ignore_patterns("__pycache__"))
            command = [sys.executable, "-m", "unittest", "discover", "-s", "tests", "-v"]
            initial = subprocess.run(command, cwd=root, capture_output=True, text=True, timeout=15)
            self.assertNotEqual(initial.returncode, 0)
            self.assertIn("NotImplementedError", initial.stderr)
            shutil.copyfile(PROJECT_ROOT / "reference" / "expenses.py", root / "expenses.py")
            # Remove only this temporary project's generated bytecode before loading the reference.
            shutil.rmtree(root / "__pycache__", ignore_errors=True)
            verified = subprocess.run(command, cwd=root, capture_output=True, text=True, timeout=15)
            self.assertEqual(verified.returncode, 0, verified.stderr)
            self.assertIn("Ran 13 tests", verified.stderr)


class FoundationsAPITests(unittest.TestCase):
    setUp = test_academy.AcademyTests.setUp
    tearDown = test_academy.AcademyTests.tearDown
    register = test_academy.AcademyTests.register
    other_learner = test_academy.AcademyTests.other_learner

    def test_module_counts_next_lesson_and_private_answers(self):
        data = self.client.get("/api/curriculum").json()
        self.assertEqual(data["lessons"][0]["id"], "python-start")
        self.assertEqual(
            sum(lesson["exercise_count"] for lesson in data["lessons"]),
            sum(len(lesson["exercises"]) for lesson in lessons()),
        )
        self.assertEqual(data["modules"][0]["project_id"], "python-expenses")
        for lesson in FOUNDATIONS:
            response = self.client.get(f"/api/lessons/{lesson['id']}")
            self.assertEqual(response.status_code, 200)
            self.assertEqual(response.json()["exercise_count"], 2)
            self.assertTrue(
                all("answer" not in e and "solution" not in e for e in response.json()["exercises"])
            )
        self.client.put("/api/lessons/python-start/complete")
        dashboard = self.client.get("/api/dashboard").json()
        self.assertEqual(dashboard["next_lesson"]["id"], "python-values")
        self.assertEqual(dashboard["mastery"], 0)

    def test_download_is_authenticated_and_contains_only_starter_files(self):
        path = "/api/projects/python-expenses/starter"
        with TestClient(app) as anonymous:
            self.assertEqual(anonymous.get(path).status_code, 401)
        response = self.client.get(path)
        self.assertEqual(response.status_code, 200)
        self.assertEqual(response.headers["content-type"], "application/zip")
        self.assertIn("attachment", response.headers["content-disposition"])
        with ZipFile(io.BytesIO(response.content)) as archive:
            self.assertEqual(
                set(archive.namelist()),
                {
                    f"expense-tracker/{name}"
                    for name in [
                        "README.md",
                        "expenses.py",
                        "cli.py",
                        "sample.csv",
                        "expected.json",
                        "tests/test_expenses.py",
                    ]
                },
            )
            self.assertIn(b"NotImplementedError", archive.read("expense-tracker/expenses.py"))
            self.assertNotIn(b"def parse_amount(text):", archive.read("expense-tracker/README.md"))
        self.assertEqual(self.client.get("/api/projects/reference/starter").status_code, 404)
        self.assertEqual(self.client.get("/api/projects/backend/starter").status_code, 404)

    def test_project_evidence_is_scoped_and_does_not_increase_mastery(self):
        path = "/api/projects/python-expenses/tasks/setup"
        self.assertEqual(self.client.put(path, json={"enabled": True}).status_code, 200)
        project = next(p for p in self.client.get("/api/projects").json() if p["id"] == "python-expenses")
        self.assertTrue(project["tasks"][0]["completed"])
        other = next(
            p for p in self.other_learner().get("/api/projects").json() if p["id"] == "python-expenses"
        )
        self.assertFalse(other["tasks"][0]["completed"])
        self.assertEqual(self.client.get("/api/dashboard").json()["mastery"], 0)
