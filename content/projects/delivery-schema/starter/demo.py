def facts(engine: Engine) -> list[dict[str, str | int]]:
    with engine.connect() as connection:
        return [
            dict(
                namespace=str(row[0]),
                id=str(row[1]),
                revision=int(row[2]),
                value=int(row[3]),
                ingested_at=str(row[4]),
            )
            for row in connection.execute(
                text(
                    "SELECT namespace,id,revision,value,ingested_at FROM feed_record ORDER BY namespace,id,revision"
                )
            )
        ]


def run_demo() -> dict[str, object]:
    dsn = os.environ.get("ACADEMY_SCHEMA_DSN")
    if not dsn:
        raise RuntimeError("choose an explicitly disposable database")
    admin = psycopg2.connect(dsn, connect_timeout=5)
    schema = "schema_demo_" + uuid.uuid4().hex
    namespace = "schema-" + uuid.uuid4().hex[:16]
    engine = None
    client = Redis.from_url(
        os.environ["ACADEMY_BROKER_URL"],
        decode_responses=False,
        socket_timeout=2,
        socket_connect_timeout=2,
        retry=Retry(NoBackoff(), 0),
    )
    try:
        with admin, admin.cursor() as cursor:
            cursor.execute(sql.SQL("CREATE SCHEMA {}").format(sql.Identifier(schema)))
        values = parse_dsn(dsn)
        values["options"] = "-csearch_path=" + schema
        engine = make_engine(url_from_dsn(make_dsn(**values)))
        service_upgrade(engine)
        with engine.begin() as connection:
            connection.execute(text("INSERT INTO feed_source VALUES (:ns)"), {"ns": namespace})
            connection.execute(
                text(
                    "INSERT INTO feed_record(namespace,id,revision,value,ingested_at) VALUES (:ns,'a',1,0,'2020-01-01T00:00:00Z'),(:ns,'a',2,9,'2020-01-02T00:00:00Z')"
                ),
                {"ns": namespace},
            )
        before = facts(engine)
        upgrade(engine)
        check(engine)
        after = facts(engine)
        assert before == after
        with engine.connect() as connection:
            assert connection.execute(text("SELECT count(*) FROM delivery_outbox")).scalar_one() == 0
        # No implicit enqueue: explicitly adopt matching old facts.
        adoption = record(engine, namespace, [Datum("a", 1, 0), Datum("a", 2, 9)])
        broker = RedisBroker(client)
        broker.setup(namespace, "effects")
        for _ in range(2):
            lease = claim(engine, namespace, Policy(100, 3, (0, 0)))
            assert lease is not None and settle(engine, lease, publisher(broker)(lease.event))
            assert deliver(engine, broker, namespace, "effects", "consumer").acknowledged
        broker.append(namespace, encode(Event(namespace, "a", 2, 9), version=1))
        assert deliver(engine, broker, namespace, "effects", "duplicate").acknowledged
        delivered = state(engine, namespace)
        check(engine)
        with engine.begin() as connection:
            connection.exec_driver_sql("DROP INDEX delivery_job_ready")
        head_during_drift = inspect_state(engine).at_head
        try:
            check(engine)
        except AutogenerateDiffsDetected:
            detected = True
        else:
            raise AssertionError("missing index was not detected")
        with engine.begin() as connection:
            connection.exec_driver_sql(
                "CREATE INDEX delivery_job_ready ON delivery_job(namespace,next_at,id,revision) WHERE state='ready'"
            )
        check(engine)
        token = secrets.token_urlsafe(32)

        async def previous() -> dict[str, object]:
            async with httpx.AsyncClient(
                transport=httpx.ASGITransport(app=create_app(engine, {token: namespace})),
                base_url="http://local.test",
            ) as app:
                headers = {"Authorization": "Bearer " + token}
                unauthorized = await app.get(f"/namespaces/{namespace}/readings")
                forbidden = await app.get("/namespaces/other/readings", headers=headers)
                allowed = await app.get(f"/namespaces/{namespace}/readings", headers=headers)
                old_ready = await app.get("/ready")
                return dict(
                    unauthorized=unauthorized.status_code,
                    forbidden=forbidden.status_code,
                    allowed=allowed.status_code,
                    old_ready=old_ready.status_code,
                    items=allowed.json()["items"],
                )

        previous_api = asyncio.run(previous())
        downgrade(engine, "delivery_003", allow_loss=True)
        after_worker_drop = dict(
            revisions=list(inspect_state(engine).revisions),
            tables=sorted(inspect(engine).get_table_names()),
            facts_preserved=facts(engine) == before,
            state=state(engine, namespace),
        )
        downgrade(engine, "service_002", allow_loss=True)
        after_history_drop = dict(
            revisions=list(inspect_state(engine).revisions),
            tables=sorted(inspect(engine).get_table_names()),
            facts_preserved=facts(engine) == before,
        )
        upgrade(engine)
        check(engine)
        empty = state(engine, namespace)
        repeated = consume(engine, Event(namespace, "a", 2, 9))
        assert repeated.event == Event(namespace, "a", 2, 9) and facts(engine) == before
        reapplied = state(engine, namespace)["applied"] == 1 and state(engine, namespace)["total"] == 9
        assert isinstance(engine.pool, QueuePool)
        return dict(
            schema="2026.10-delivery-schema-v1",
            server_version=admin.server_version,
            versions={
                name: version(name)
                for name in [
                    "academy-ingestion-service-lab",
                    "academy-competing-ingestion-lab",
                    "academy-durable-outbox-lab",
                    "academy-leased-worker-lab",
                    "academy-stream-delivery-lab",
                    "academy-delivery-schema-lab",
                    "alembic",
                    "SQLAlchemy",
                    "redis",
                ]
            },
            before_facts=before,
            after_facts=after,
            final_facts=facts(engine),
            head=list(inspect_state(engine).revisions),
            adoption=dict(
                inserted=adoption.receipt.inserted,
                duplicates=adoption.receipt.duplicates,
                enqueued=adoption.enqueued,
            ),
            delivered=delivered,
            drift=dict(
                head_only=head_during_drift,
                missing_index_detected=detected,
                scope="autogenerate comparison; CHECK expression/data invariants not established",
            ),
            worker_rollback=after_worker_drop,
            history_rollback=after_history_drop,
            after_reupgrade=empty,
            same_key_can_apply_after_history_loss=reapplied,
            previous_api=previous_api,
            checked_out_connections=engine.pool.checkedout(),
            scope="finite PostgreSQL migration/rollback and Redis composition rehearsal; not deployment or backup recovery",
        )
    finally:
        try:
            client.delete(stream(namespace))
        finally:
            client.close()
            if engine is not None:
                engine.dispose()
            admin.rollback()
            admin.autocommit = True
            try:
                with admin.cursor() as cursor:
                    cursor.execute(sql.SQL("DROP SCHEMA {} CASCADE").format(sql.Identifier(schema)))
            finally:
                admin.close()


if __name__ == "__main__":
    parser = argparse.ArgumentParser()
    parser.add_argument("--output", type=Path)
    args = parser.parse_args()
    report = run_demo()
    payload = json.dumps(report, indent=2) + "\n"
    if args.output:
        args.output.write_text(payload)
    print(payload, end="")
