@pytest.mark.parametrize("damage", ["column", "index", "default", "extra"])
def test_head_only_does_not_detect_autogenerate_drift(engine, damage):
    upgrade(engine)
    sql = {
        "column": "ALTER TABLE delivery_effect ADD COLUMN stray integer",
        "index": "DROP INDEX delivery_job_ready",
        "default": "ALTER TABLE delivery_job ALTER COLUMN state SET DEFAULT 'dead'",
        "extra": "CREATE TABLE stray (value integer)",
    }[damage]
    with engine.begin() as connection:
        connection.exec_driver_sql(sql)
    assert inspect_state(engine).at_head
    upgrade(engine)  # Already-head is not repair.
    with pytest.raises(AutogenerateDiffsDetected):
        check(engine)
    assert inspect_state(engine).at_head


