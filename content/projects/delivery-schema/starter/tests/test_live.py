def facts(engine):
    with engine.connect() as connection:
        return [
            tuple(row)
            for row in connection.execute(
                text(
                    "SELECT namespace,id,revision,value,ingested_at FROM feed_record ORDER BY namespace,id,revision"
                )
            )
        ]


def seed_old(engine):
    old_upgrade(engine)
    with engine.begin() as connection:
        connection.execute(text("INSERT INTO feed_source VALUES ('scope')"))
        connection.execute(
            text(
                "INSERT INTO feed_record(namespace,id,revision,value,ingested_at) VALUES ('scope','a',1,0,'2020-01-01T00:00:00Z'), ('scope','a',2,9,'2020-01-02T00:00:00Z')"
            )
        )
    return facts(engine)


def test_fresh_upgrade_and_combined_drift(engine):
    assert inspect_state(engine).revisions == ()
    with pytest.raises(NotReady):
        check(engine)
    upgrade(engine)
    check(engine)
    assert inspect_state(engine).revisions == (HEAD,)
    assert len(inspect(engine).get_table_names()) == 8
    assert isinstance(engine.pool, QueuePool) and engine.pool.checkedout() == 0


def test_existing_timestamped_facts_survive_each_revision(engine):
    before = seed_old(engine)
    upgrade(engine, "delivery_003")
    assert inspect_state(engine).revisions == ("delivery_003",)
    assert facts(engine) == before
    with engine.connect() as connection:
        assert connection.execute(text("SELECT count(*) FROM delivery_outbox")).scalar_one() == 0
    upgrade(engine)
    check(engine)
    assert facts(engine) == before
    upgrade(engine)
    assert facts(engine) == before


def test_downgrade_preserves_facts_but_explicitly_loses_history(engine):
    before = seed_old(engine)
    upgrade(engine)
    record(engine, "scope", [Datum("a", 1, 0), Datum("a", 2, 9)])
    lease = claim(engine, "scope", Policy(100, 3, (0, 0)))
    assert lease is not None
    consume(engine, lease.event)
    with pytest.raises(ValueError):
        downgrade(engine, "service_002")
    assert inspect_state(engine).at_head
    downgrade(engine, "delivery_003", allow_loss=True)
    assert facts(engine) == before
    assert "delivery_job" not in inspect(engine).get_table_names()
    assert state(engine, "scope")["inbox"] == 1
    downgrade(engine, "service_002", allow_loss=True)
    assert facts(engine) == before
    assert set(inspect(engine).get_table_names()) == {"alembic_version", "feed_source", "feed_record"}
    upgrade(engine)
    check(engine)
    assert facts(engine) == before and state(engine, "scope")["inbox"] == 0
    # Broker replay after history loss can apply the same key again.
    assert consume(engine, Event("scope", "a", 1, 0)).event == Event("scope", "a", 1, 0)
    assert state(engine, "scope")["applied"] == 1


