def test_limits_and_connection_are_released_after_failure(engine):
    seed_old(engine)
    with engine.connect() as connection:
        before = tuple(
            connection.execute(
                text("SELECT current_setting('lock_timeout'),current_setting('statement_timeout')")
            ).one()
        )
    with engine.begin() as connection:
        connection.exec_driver_sql("CREATE TABLE worker_policy(x integer)")
    with pytest.raises(DBAPIError):
        upgrade(engine)
    with engine.connect() as connection:
        assert (
            tuple(
                connection.execute(
                    text("SELECT current_setting('lock_timeout'),current_setting('statement_timeout')")
                ).one()
            )
            == before
        )
        assert (
            connection.execute(text("SELECT pg_try_advisory_xact_lock(:key)"), {"key": LOCK}).scalar_one()
            is True
        )
    assert engine.pool.checkedout() == 0


def test_previous_business_permissions_and_old_readiness_are_explicit(engine):
    seed_old(engine)
